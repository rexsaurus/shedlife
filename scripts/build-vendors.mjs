// data/wa-vendors.json (researched, cited) → src/data/vendors.js (importable by Vite and Node). Run after editing the JSON.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const rows = JSON.parse(readFileSync(new URL('../data/wa-vendors.json', import.meta.url)));
mkdirSync(new URL('../src/data/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/data/vendors.js', import.meta.url), `// GENERATED by scripts/build-vendors.mjs from data/wa-vendors.json — do not edit by hand.\nexport default ${JSON.stringify(rows, null, 1)};\n`);
console.log(`${rows.length} vendor products`);
